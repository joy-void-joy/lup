# lup: ignore[constant-declaration]
# Both constants here are this application's own composition — what its CLI
# declines from the library, and what only it has. A composition root is where
# a judgement is finally made rather than passed on, so there is no caller
# above it to take these from.
"""This application's sub-app delta: what it declines, and what only it has.

The library ships the whole roster and a project states the difference, rather
than restating the list. That inversion is the point: the two halves of lup
reach a project by different routes — the library through a lock refresh, this
file through a hand-replayed commit — so a roster enumerated here would go on
naming what lup shipped the day it was copied, and the sub-app that arrived
afterwards would be missing without anyone having decided it should be.

Only specs here, never Typer apps. Documents under ``harness/content/``
describe this CLI and are themselves generated by it, so a roster that reached
for the wired apps to learn their names would make the guidance depend on the
tooling that renders it. ``devtools/main.py`` is where each name meets the app
that answers to it, and nothing imports ``main``.
"""

from lup.devtools.roster import LIBRARY_SPECS
from lup.devtools.subapps import SubAppSelection, SubAppSpec

SELECTION = SubAppSelection()
"""Which of lup's own sub-apps this CLI declines to serve.

Empty, because lup authors them: a template declining one of its own would be
saying it should not have been written. The seat is what a project adopting
this scaffold fills — one line naming what it declines, against a roster that
goes on growing underneath it."""

APPLICATION_SPECS = [
    SubAppSpec(name="agent", help="Agent introspection and debugging"),
]
"""The sub-apps only this application has, because only it has their subject."""

SUBAPP_SPECS = SELECTION.specs(LIBRARY_SPECS, APPLICATION_SPECS)
"""Every sub-app this CLI serves, in the order `--help` lists them."""
